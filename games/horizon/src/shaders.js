// Horizon — GLSL shaders (Three.js ShaderMaterial, WebGL1-friendly)
window.HORIZON_VERT = [
  'varying vec2 vUv;',
  'void main(){',
  '  vUv = uv;',
  '  gl_Position = vec4(position.xy, 0.0, 1.0);',
  '}'
].join('\n');

window.HORIZON_FRAG = [
'precision highp float;',
'varying vec2 vUv;',
'uniform vec2 uRes;',
'uniform float uTime;',
'uniform float uSpin;',
'uniform float uCamDist;',
'uniform float uCamTheta;',
'uniform float uCamPhi;',
'uniform float uFov;',
'uniform float uSteps;',
'uniform float uStepScale;',
'uniform float uMode;',
'uniform float uFallT;',
'uniform vec3 uProbePos[8];',
'uniform float uProbeAge[8];',
'uniform float uProbeCount;',
'uniform vec3 uLaserOrigin;',
'uniform vec3 uLaserDir;',
'uniform float uLaserOn;',
'uniform float uCompare;',
'uniform float uBloom;',
'uniform float uExposure;',
'',
'#define PI 3.14159265',
'#define M 1.0',
'#define RS 2.0',
'',
'float hash(vec2 p){ return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453); }',
'float hash3(vec3 p){ return fract(sin(dot(p,vec3(127.1,311.7,74.7)))*43758.5453); }',
'float noise(vec2 p){',
'  vec2 i=floor(p), f=fract(p);',
'  float a=hash(i), b=hash(i+vec2(1.,0.)), c=hash(i+vec2(0.,1.)), d=hash(i+vec2(1.,1.));',
'  vec2 u=f*f*(3.-2.*f);',
'  return mix(a,b,u.x)+(c-a)*u.y*(1.-u.x)+(d-b)*u.x*u.y;',
'}',
'float fbm(vec2 p){ float v=0.,a=.5; for(int i=0;i<5;i++){v+=a*noise(p);p=p*2.11+vec2(3.1,1.7);a*=.5;} return v; }',
'',
'vec3 milkyWay(vec3 d){',
'  d=normalize(d);',
'  float lat=d.y;',
'  float lon=atan(d.z,d.x);',
'  float band=exp(-pow(lat*2.8,2.0));',
'  float dust=fbm(vec2(lon*1.2,lat*3.5)*2.0);',
'  vec3 mw=vec3(0.45,0.55,0.95)*band*(0.25+0.75*dust)*0.7;',
'  mw+=vec3(1.0,0.8,0.55)*band*dust*dust*0.45;',
'  float bulge=exp(-pow(length(vec2(lon,lat*1.8))*1.6,2.0));',
'  mw+=vec3(1.0,0.85,0.6)*bulge*0.55;',
'  float s=0.0;',
'  for(int i=0;i<4;i++){',
'    float sc=exp2(float(i)+6.0);',
'    vec3 id=floor(d*sc);',
'    float h=hash3(id);',
'    if(h>0.96){',
'      vec3 f=fract(d*sc)-0.5;',
'      float r2=dot(f,f);',
'      s+=pow(h,20.0)*smoothstep(0.08,0.0,sqrt(r2))*(1.0+3.0*step(0.992,h));',
'    }',
'  }',
'  vec3 scol=mix(vec3(0.7,0.85,1.0),vec3(1.0,0.8,0.55),hash3(d*9.1));',
'  return mw + scol*s*1.8 + vec3(0.008,0.01,0.018);',
'}',
'',
'vec3 tempRGB(float t){',
'  t=clamp(t,1000.0,14000.0)/1000.0;',
'  vec3 c;',
'  c.r=t<6.6?1.0:clamp(1.2929*pow(t-6.0,-0.1332),0.0,1.0);',
'  c.g=t<6.6?clamp(0.3901*log(t)-0.6318,0.0,1.0):clamp(1.1295*pow(t-6.0,-0.0755),0.0,1.0);',
'  c.b=t>=6.6?1.0:(t<=2.0?0.0:clamp(0.5433*log(t-1.0)-1.196,0.0,1.0));',
'  return c;',
'}',
'',
'float isco(float a){',
'  a=clamp(a,0.0,0.998);',
'  float z1=1.0+pow(1.0-a*a,1.0/3.0)*(pow(1.0+a,1.0/3.0)+pow(1.0-a,1.0/3.0));',
'  float z2=sqrt(3.0*a*a+z1*z1);',
'  return 3.0+z2-sqrt((3.0-z1)*(3.0+z1+2.0*z2));',
'}',
'float horizonR(float a){ return 1.0+sqrt(max(1.0-a*a,0.0)); }',
'',
'vec3 geodesicAccel(vec3 p, vec3 v, float a){',
'  float r=length(p);',
'  float soft=max(r,0.2);',
'  vec3 h=cross(p,v);',
'  float h2=dot(h,h);',
'  vec3 acc=-1.5*RS*h2*p/pow(soft,5.0);',
'  float omega=2.0*a*M/(soft*soft*soft + 0.5*a*a*soft);',
'  vec3 axis=vec3(0.0,1.0,0.0);',
'  acc+=-2.0*omega*cross(axis,v);',
'  acc+=cross(axis,p)*omega*0.55*a;',
'  acc+=-normalize(p+1e-5)*(a*h.y*0.4)/(soft*soft*soft);',
'  return acc;',
'}',
'',
'void integrate(inout vec3 p, inout vec3 v, float a, float dt){',
'  vec3 a1=geodesicAccel(p,v,a);',
'  vec3 p2=p+v*dt;',
'  vec3 v2=v+a1*dt;',
'  vec3 a2=geodesicAccel(p2,v2,a);',
'  p+=0.5*dt*(v+v2);',
'  v+=0.5*dt*(a1+a2);',
'}',
'',
'vec3 sampleDisk(vec3 p, vec3 viewV, float a){',
'  float rho=length(p.xz);',
'  float rin=isco(a);',
'  float rout=16.0;',
'  if(rho<rin||rho>rout) return vec3(0.0);',
'  float phi=atan(p.z,p.x);',
'  float omegaK=1.0/(pow(rho,1.5)+a);',
'  float u=phi*2.5 - uTime*omegaK*3.5;',
'  float turb=fbm(vec2(rho*0.35-uTime*0.08, u*0.55));',
'  float turb2=fbm(vec2(rho*0.8, u*0.9+2.0));',
'  float dens=smoothstep(rin,rin+0.6,rho)*smoothstep(rout,rout*0.5,rho);',
'  dens*=(0.55+0.45*turb)*(0.65+0.35*turb2);',
'  float temp=8500.0*pow(rin/max(rho,rin),0.75)*(0.7+0.3*turb);',
'  vec3 base=tempRGB(temp);',
'  vec3 vDisk=vec3(-p.z,0.0,p.x);',
'  float vlen=length(vDisk)+1e-5;',
'  vDisk/=vlen;',
'  float beta=clamp(0.45*rho*omegaK,0.0,0.75);',
'  float mu=dot(normalize(-viewV),vDisk);',
'  float gamma=1.0/sqrt(max(1.0-beta*beta,1e-4));',
'  float delta=clamp(1.0/(gamma*(1.0-beta*mu)),0.2,3.8);',
'  float zg=sqrt(max(1.0-RS/max(rho,RS*1.02),0.04));',
'  float z=zg*delta;',
'  vec3 col=base*pow(z,3.0);',
'  col*=mix(vec3(1.35,0.75,0.45),vec3(0.5,0.8,1.45),smoothstep(0.6,1.5,delta));',
'  float inten=dens*4.6*pow(rin/max(rho,0.4),0.95);',
'  return col*inten;',
'}',
'',
'vec3 trace(vec3 ro, vec3 rd, float a, float steps){',
'  vec3 p=ro;',
'  vec3 v=normalize(rd);',
'  vec3 col=vec3(0.0);',
'  float tr=1.0;',
'  float rh=horizonR(a);',
'  bool caught=false;',
'',
'  for(int i=0;i<200;i++){',
'    if(float(i)>=steps) break;',
'    float r=length(p);',
'    if(r<rh*1.02){ caught=true; break; }',
'    if(r>100.0 && i>4){ col+=tr*milkyWay(v); break; }',
'',
'    float dt=clamp(0.065*uStepScale*r, 0.025, 1.1);',
'',
'    float ay=abs(p.y);',
'    float thick=0.22+0.06*fbm(p.xz*0.4);',
'    if(ay<thick){',
'      float w=smoothstep(thick,0.0,ay);',
'      vec3 dcol=sampleDisk(vec3(p.x,0.0,p.z),v,a);',
'      col+=dcol*w*tr;',
'      tr*=1.0-clamp(length(dcol)*0.22*w,0.0,0.7);',
'      if(tr<0.02) break;',
'    }',
'',
'    float ph=3.0;',
'    if(r>rh*1.05 && r<ph*1.55){',
'      float ring=exp(-pow((r-ph)*3.0,2.0));',
'      vec3 eq=vec3(p.x,0.0,p.z);',
'      float el=length(eq);',
'      if(el>0.2){',
'        vec3 rp=eq/el*ph;',
'        col+=tr*ring*sampleDisk(rp,v,a)*0.28;',
'        col+=tr*ring*milkyWay(v)*0.14;',
'      }',
'    }',
'',
'    integrate(p,v,a,dt);',
'  }',
'',
'  if(caught){',
'    col*=0.02;',
'  } else {',
'    float rEnd=length(p);',
'    if(rEnd<6.0 && dot(normalize(p),normalize(v))<-0.1){',
'      col*=0.02;',
'    } else if(tr>0.04){',
'      col+=tr*milkyWay(normalize(v));',
'    }',
'  }',
'  return col;',
'}',
'',
'void camRay(vec2 uv, out vec3 ro, out vec3 rd){',
'  float ct=cos(uCamTheta), st=sin(uCamTheta);',
'  float cp=cos(uCamPhi), sp=sin(uCamPhi);',
'  ro=uCamDist*vec3(st*cp, ct, st*sp);',
'  vec3 fwd=normalize(-ro);',
'  vec3 up0=vec3(0.0,1.0,0.0);',
'  vec3 right=normalize(cross(fwd,up0));',
'  if(dot(right,right)<1e-4) right=vec3(1.0,0.0,0.0);',
'  vec3 up=cross(right,fwd);',
'  float fov=uFov;',
'  rd=normalize(fwd+uv.x*right*fov+uv.y*up*fov);',
'',
'  if(uMode>2.5 || uFallT>0.001){',
'    float t=uFallT;',
'    float dist=mix(uCamDist,0.55,pow(clamp(t,0.0,1.0),0.65));',
'    ro=normalize(ro+1e-5)*dist;',
'    fwd=normalize(-ro);',
'    right=normalize(cross(fwd,up0));',
'    up=cross(right,fwd);',
'    float fov2=mix(fov,fov*1.7,t);',
'    rd=normalize(fwd+uv.x*right*fov2+uv.y*up*fov2);',
'    float ang=t*t*uSpin*4.0;',
'    float ca=cos(ang), sa=sin(ang);',
'    rd=vec3(ca*rd.x-sa*rd.z, rd.y, sa*rd.x+ca*rd.z);',
'  }',
'}',
'',
'vec3 fabric(vec2 uv){',
'  vec2 q=uv*12.0;',
'  float r=length(q);',
'  float a=uSpin;',
'  float rh=horizonR(a);',
'  float phi=atan(q.y,q.x)-a*2.2/max(r,0.4);',
'  float rings=abs(sin(r*2.6));',
'  float spokes=abs(sin(phi*8.0));',
'  float grid=smoothstep(0.1,0.0,rings*0.55)+smoothstep(0.08,0.0,spokes*0.5);',
'  vec3 col=vec3(0.015,0.03,0.06);',
'  col+=vec3(0.3,0.6,1.0)*grid*0.55;',
'  col+=vec3(1.0,0.45,0.2)*smoothstep(0.14,0.0,abs(r-rh))*1.3;',
'  if(a>0.05) col+=vec3(0.7,0.35,1.0)*smoothstep(0.16,0.0,abs(r-RS))*0.55*a;',
'  float rip=sin(r*6.0-uTime*4.0)*exp(-r*0.12);',
'  col+=vec3(0.5,0.85,1.0)*max(rip,0.0)*0.18;',
'  float z=r>rh?-2.0*log(max(r/RS,1.001)):-4.0;',
'  col*=0.5+0.5*clamp(1.0+z*0.12,0.0,1.0);',
'  return col;',
'}',
'',
'float probeGlow(vec3 ro, vec3 rd){',
'  float g=0.0;',
'  for(int i=0;i<8;i++){',
'    if(float(i)>=uProbeCount) break;',
'    vec3 pp=uProbePos[i];',
'    vec3 oc=ro-pp;',
'    float b=dot(oc,rd);',
'    float c=dot(oc,oc);',
'    float glow=exp(-2.5*abs(b))/(0.25+c);',
'    float r=length(pp);',
'    float rh=horizonR(uSpin);',
'    float zf=clamp((r-rh)/4.0,0.0,1.0);',
'    g+=glow*(0.35+0.65*zf)*exp(-uProbeAge[i]*0.02);',
'  }',
'  return g;',
'}',
'',
'vec3 ACES(vec3 x){',
'  x*=uExposure;',
'  float a=2.51,b=0.03,c=2.43,d=0.59,e=0.14;',
'  return clamp((x*(a*x+b))/(x*(c*x+d)+e),0.0,1.0);',
'}',
'',
'void main(){',
'  vec2 uv=(vUv*2.0-1.0);',
'  uv.x*=uRes.x/uRes.y;',
'',
'  if(uMode>1.5 && uMode<2.5){',
'    vec3 col=fabric(uv);',
'    col*=1.0-0.3*dot(uv,uv);',
'    gl_FragColor=vec4(ACES(col*1.5),1.0);',
'    return;',
'  }',
'',
'  vec3 ro, rd;',
'  camRay(uv, ro, rd);',
'',
'  float a=uSpin;',
'  if(uCompare>0.5 && vUv.x<0.5) a=0.0;',
'',
'  vec3 col=trace(ro, rd, a, uSteps);',
'',
'  float pg=probeGlow(ro,rd);',
'  col+=vec3(1.0,0.45,0.2)*pg*1.6;',
'',
'  if(uMode>0.5 && uMode<1.5 && uLaserOn>0.5){',
'    vec3 lp=uLaserOrigin;',
'    vec3 lv=normalize(uLaserDir);',
'    float glow=0.0;',
'    for(int k=0;k<72;k++){',
'      float r=length(lp);',
'      if(r<horizonR(a)*1.02||r>75.0) break;',
'      vec3 w=lp-ro;',
'      float t=clamp(dot(w,rd),0.0,120.0);',
'      float dist=length(w-rd*t);',
'      glow+=exp(-dist*dist*55.0)*0.4;',
'      float dt=clamp(0.06*uStepScale*r,0.03,0.9);',
'      integrate(lp,lv,a,dt);',
'    }',
'    col+=vec3(0.35,1.0,0.6)*glow;',
'  }',
'',
'  if(uFallT>0.01){',
'    float red=mix(1.0,0.12,smoothstep(0.25,0.95,uFallT));',
'    col*=vec3(1.0,red,red*red);',
'    col+=milkyWay(rd)*uFallT*0.35;',
'    if(uFallT>0.9) col=mix(col,vec3(1.0,0.95,0.88),smoothstep(0.9,1.0,uFallT)*0.85);',
'  }',
'',
'  if(uCompare>0.5){',
'    float d=abs(vUv.x-0.5);',
'    col=mix(col,vec3(0.85),smoothstep(0.0035,0.0,d));',
'  }',
'',
'  float vig=1.0-0.32*dot(uv*0.85,uv*0.85);',
'  col*=vig;',
'  float lum=dot(col,vec3(0.3,0.5,0.2));',
'  col+=col*smoothstep(0.5,2.2,lum)*uBloom*0.4;',
'  col=ACES(col);',
'  col=pow(max(col,0.0),vec3(0.92));',
'  gl_FragColor=vec4(col,1.0);',
'}'
].join('\n');
